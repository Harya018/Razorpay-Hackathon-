# One consistent warm palette for every product image — matches the
# storefront's own design tokens (storefront-tokens.css) directly, rather
# than a different flat color swatch per item.
_BG_TOP = "#f2ede3"  # ivory
_BG_BOTTOM = "#e5dac9"  # putty-light
_RING = "#8b6552"  # clay
_INK = "#2b2823"  # ink


def _placeholder_svg(emoji: str, name: str, variant: int) -> str:
    # `variant` only nudges the stamp ring's rotation across a product's
    # own gallery images so thumbnails aren't pixel-identical — it never
    # changes the palette, so every product's images still read as the
    # same shop's shelf, not a different colored swatch per item.
    rotation = (variant - 1) * 11
    lines = textwrap.wrap(name, width=18)[:2]
    tspans = "".join(
        f'<tspan x="350" dy="{0 if i == 0 else 36}">{_xml_escape(line)}</tspan>' for i, line in enumerate(lines)
    )
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" width="700" height="700">'
        "<defs><linearGradient id=\"bg\" x1=\"0\" y1=\"0\" x2=\"0\" y2=\"1\">"
        f'<stop offset="0" stop-color="{_BG_TOP}"/><stop offset="1" stop-color="{_BG_BOTTOM}"/>'
        "</linearGradient></defs>"
        f'<rect width="700" height="700" fill="url(#bg)"/>'
        f'<circle cx="350" cy="280" r="175" fill="none" stroke="{_RING}" stroke-width="2.5" '
        f'stroke-dasharray="3 11" transform="rotate({rotation} 350 280)"/>'
        f'<text x="350" y="290" font-size="150" text-anchor="middle" dominant-baseline="middle">{emoji}</text>'
        f'<text x="350" y="470" font-size="33" font-family="Georgia, \'Times New Roman\', serif" '
        f'font-weight="600" fill="{_INK}" text-anchor="middle">{tspans}</text>'
        "</svg>"
    )
    encoded = base64.b64encode(svg.encode("utf-8")).decode("ascii")
    return f"data:image/svg+xml;base64,{encoded}"


def placeholder_images(emoji: str, name: str, n: int = 2) -> list[str]:
    return [_placeholder_svg(emoji, name, i) for i in range(1, n + 1)]


