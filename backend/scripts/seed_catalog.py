def seed():
    db = SessionLocal()
    created, updated, removed = 0, 0, 0
    try:
        touched_ids = set()
        for raw in PRODUCTS:
            data = dict(raw)
            old_name = data.pop("match_name", None)
            # Bug fixed Phase 20: a match_name lookup only ever finds the
            # OLD name, so a second run (after the first already renamed
            # the row) found nothing, created a duplicate with a fresh ID,
            # and deleted the real row — silently orphaning every order's
            # product_id FK. Falling back to the current `name` makes the
            # match_name lookup idempotent across repeat runs.
            existing = None
            if old_name:
                existing = db.query(Product).filter(Product.name == old_name).first()
            if existing is None:
                existing = db.query(Product).filter(Product.name == data["name"]).first()
            if existing:
                for key, value in data.items():
                    setattr(existing, key, value)
                db.flush()
                touched_ids.add(existing.id)
                updated += 1
            else:
                obj = Product(**data)
                db.add(obj)
                db.flush()
                touched_ids.add(obj.id)
                created += 1

        # Anything left over is a pre-Phase-17 SKU (the old electronics/
        # footwear/fitness/stationery catalog) that isn't part of Priya's
        # Shop's handmade-decor lineup — remove it so the storefront and
        # admin catalog only ever show real decor items.
        stale = db.query(Product).filter(~Product.id.in_(touched_ids)).all()
        for p in stale:
            db.delete(p)
            removed += 1

        db.commit()
    finally:
        db.close()
    print(f"Seed complete: {created} created, {updated} updated, {removed} removed, {len(PRODUCTS)} total.")


if __name__ == "__main__":
    seed()
